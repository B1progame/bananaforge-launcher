const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("bananaforge", {
  getState: () => ipcRenderer.invoke("state:get"),
  getMelonLoaderRecommendation: (force = false) => ipcRenderer.invoke('loader:recommendation', force),
  openProfileDialog: () => ipcRenderer.invoke("profile-dialog:open"),
  closeProfileDialog: () => ipcRenderer.invoke("profile-dialog:close"),
  saveSettings: (settings) => ipcRenderer.invoke("settings:save", settings),
  chooseGame: () => ipcRenderer.invoke("dialog:game"),
  chooseFolder: (title) => ipcRenderer.invoke("dialog:folder", title),
  chooseMelonLoader: () => ipcRenderer.invoke("dialog:melonloader"),
  createManagedCopy: () => ipcRenderer.invoke("instance:create-copy"),
  startSetup: (options) => ipcRenderer.invoke('setup:start', options),
  cancelSetup: () => ipcRenderer.invoke('setup:cancel'),
  launchGame: () => ipcRenderer.invoke("game:launch"),
  closeGame: () => ipcRenderer.invoke('game:close'),
  reportRendererError: (message) => ipcRenderer.send('renderer:error', String(message || '').slice(0, 2000)),
  updateGame: () => ipcRenderer.invoke("game:update"),
  checkAppUpdate: () => ipcRenderer.invoke('app:update-check'),
  installAppUpdate: () => ipcRenderer.invoke('app:update-install'),
  checkGameUpdate: () => ipcRenderer.invoke('game:check-update'),
  launchMelonLoader: () => ipcRenderer.invoke("melonloader:launch"),
  downloadMelonLoader: () => ipcRenderer.invoke("melonloader:download"),
  createProfile: (name) => ipcRenderer.invoke("profiles:create", name),
  activateProfile: (id) => ipcRenderer.invoke("profiles:activate", id),
  deleteProfile: (id) => ipcRenderer.invoke("profiles:delete", id),
  profileDetails: (id) => ipcRenderer.invoke("profiles:details", id),
  updateProfile: (id, values) => ipcRenderer.invoke('profiles:update', id, values),
  duplicateProfile: (id) => ipcRenderer.invoke('profiles:duplicate', id),
  exportProfile: (id) => ipcRenderer.invoke('profiles:export', id),
  importProfile: () => ipcRenderer.invoke('profiles:import'),
  openProfileFolder: (id) => ipcRenderer.invoke('profiles:folder', id),
  toggleMod: (id, name, enabled) => ipcRenderer.invoke('mods:toggle', id, name, enabled),
  listLogs: () => ipcRenderer.invoke('logs:list'),
  readLog: (id) => ipcRenderer.invoke('logs:read', id),
  copyLog: (id) => ipcRenderer.invoke('logs:copy', id),
  exportLog: (id) => ipcRenderer.invoke('logs:export', id),
  showLog: (id) => ipcRenderer.invoke('logs:folder', id),
  installMods: (profileId) => ipcRenderer.invoke("mods:install", profileId),
  installDownloadedMod: (file, profileId) => ipcRenderer.invoke("mods:install-download", file, profileId),
  installModFromLink: (url, profileId) => ipcRenderer.invoke('mods:install-link', url, profileId),
  listMods: () => ipcRenderer.invoke("mods:list"),
  removeMod: (name, profileId) => ipcRenderer.invoke("mods:remove", name, profileId),
  openDownloadsFolder: () => ipcRenderer.invoke('downloads:folder'),
  cancelDownload: (id) => ipcRenderer.invoke('downloads:cancel', id),
  checkModUpdates: (profileId) => ipcRenderer.invoke('mods:auto-update', profileId),
  searchModUpdateSources: (profileId, name, searchTerm) => ipcRenderer.invoke('mods:search-update-sources', profileId, name, searchTerm),
  trackDiscoveredModUpdates: (profileId, name, repository, asset, sourceType, branch, sourcePath) => ipcRenderer.invoke('mods:track-discovered-update', profileId, name, repository, asset, sourceType, branch, sourcePath),
  trackModUpdates: (profileId, name, releaseUrl) => ipcRenderer.invoke('mods:track-update', profileId, name, releaseUrl),
  trackKnownModUpdates: (profileId, name) => ipcRenderer.invoke('mods:track-known-update', profileId, name),
  disableIncompatibleMod: (profileId, name) => ipcRenderer.invoke('mods:disable-incompatible', profileId, name),
  showPath: (target) => ipcRenderer.invoke("path:show", target),
  openExternal: (url) => ipcRenderer.invoke("external:open", url),
  onDownloadsChanged: (callback) => ipcRenderer.on("downloads:changed", (_event, value) => callback(value)),
  onProfilesChanged: (callback) => ipcRenderer.on("profiles:changed", (_event, value) => callback(value)),
  onNewTab: (callback) => ipcRenderer.on("browser:new-tab", (_event, value) => callback(value)),
  onInstanceProgress: (callback) => ipcRenderer.on("instance:progress", (_event, value) => callback(value)),
  onMelonLoaderDownloaded: (callback) => ipcRenderer.on("melonloader:downloaded", (_event, value) => callback(value))
  , onSetupProgress: (callback) => ipcRenderer.on('setup:progress', (_event, value) => callback(value))
  , onGameChanged: (callback) => ipcRenderer.on('game:changed', (_event, value) => callback(value))
  , onGameCrash: (callback) => ipcRenderer.on('game:crashed', (_event, value) => callback(value))
  , onModUpdate: (callback) => ipcRenderer.on('mods:auto-update', (_event, value) => callback(value))
  , onModWarning: (callback) => ipcRenderer.on('game:mod-warning', (_event, value) => callback(value))
  , onAppUpdateStatus: (callback) => ipcRenderer.on('app:update-status', (_event, value) => callback(value))
  , onGameAutoUpdateStatus: (callback) => ipcRenderer.on('game:auto-update-status', (_event, value) => callback(value))
});
